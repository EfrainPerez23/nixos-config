import sys

styles_path = sys.argv[1]

with open(styles_path, "r") as f:
    src = f.read()

old_imports = (
    "import Gio from 'gi://Gio';\n"
    "import St from 'gi://St';\n"
)
new_imports = (
    "import Gio from 'gi://Gio';\n"
    "import St from 'gi://St';\n"
    "import * as Main from 'resource:///org/gnome/shell/ui/main.js';\n"
    "let _cachedStyleSheet = null;\n"
    "let _cachedStyles = null;\n"
    "let _cachedTheme = null;\n"
)
assert old_imports in src, "Imports block not found in Styles.js"
src = src.replace(old_imports, new_imports, 1)

old_methods = (
    "    destroy() {\n"
    "        this._workspaceUpdateNotifier.destroy();\n"
    "        this._unloadStyleSheet();\n"
    "    }\n"
    "    _updateStyleSheet() {\n"
    "        this._unloadStyleSheet();\n"
    "        const themeContext = St.ThemeContext.get_for_stage(global.stage);\n"
    "        let styles = this._generateStyleSheetContent();\n"
    "        this._settings.applicationStyles.value = styles;\n"
    "        if (this._settings.customStylesEnabled.value) {\n"
    "            this._settings.customStylesFailed.value = false;\n"
    "            styles = styles + '\\n' + this._settings.customStyles.value;\n"
    "        }\n"
    "        const [file, stream] = Gio.File.new_tmp(null);\n"
    "        const outputStream = Gio.DataOutputStream.new(stream.outputStream);\n"
    "        outputStream.put_string(styles, null);\n"
    "        try {\n"
    "            themeContext.get_theme().load_stylesheet(file);\n"
    "        }\n"
    "        catch (e) {\n"
    "            console.error('Failed to load stylesheet');\n"
    "            if (this._settings.customStylesEnabled.value) {\n"
    "                this._settings.customStylesEnabled.value = false;\n"
    "                this._settings.customStylesFailed.value = true;\n"
    "            }\n"
    "        }\n"
    "        outputStream.close(null);\n"
    "        stream.close(null);\n"
    "        this._dynamicStyleSheet = file;\n"
    "    }\n"
    "    _unloadStyleSheet() {\n"
    "        if (this._dynamicStyleSheet) {\n"
    "            const themeContext = St.ThemeContext.get_for_stage(global.stage);\n"
    "            themeContext.get_theme().unload_stylesheet(this._dynamicStyleSheet);\n"
    "            try {\n"
    "                this._dynamicStyleSheet.delete(null);\n"
    "            }\n"
    "            catch (e) {\n"
    "                console.warn('Failed to delete temporary stylesheet file:', e);\n"
    "            }\n"
    "            this._dynamicStyleSheet = undefined;\n"
    "        }\n"
    "    }"
)

new_methods = (
    "    destroy() {\n"
    "        this._workspaceUpdateNotifier.destroy();\n"
    "        if (Main.sessionMode.isLocked || Main.sessionMode.currentMode === 'unlock-dialog') {\n"
    "            return;\n"
    "        }\n"
    "        this._unloadStyleSheet();\n"
    "    }\n"
    "    _updateStyleSheet() {\n"
    "        const themeContext = St.ThemeContext.get_for_stage(global.stage);\n"
    "        const theme = themeContext.get_theme();\n"
    "        let styles = this._generateStyleSheetContent();\n"
    "        if (this._settings.applicationStyles.value !== styles) {\n"
    "            this._settings.applicationStyles.value = styles;\n"
    "        }\n"
    "        if (this._settings.customStylesEnabled.value) {\n"
    "            this._settings.customStylesFailed.value = false;\n"
    "            styles = styles + '\\n' + this._settings.customStyles.value;\n"
    "        }\n"
    "        if (_cachedStyleSheet && _cachedTheme === theme && _cachedStyles === styles) {\n"
    "            this._dynamicStyleSheet = _cachedStyleSheet;\n"
    "            return;\n"
    "        }\n"
    "        this._unloadStyleSheet();\n"
    "        const [file, stream] = Gio.File.new_tmp(null);\n"
    "        const outputStream = Gio.DataOutputStream.new(stream.outputStream);\n"
    "        outputStream.put_string(styles, null);\n"
    "        try {\n"
    "            theme.load_stylesheet(file);\n"
    "        }\n"
    "        catch (e) {\n"
    "            console.error('Failed to load stylesheet');\n"
    "            if (this._settings.customStylesEnabled.value) {\n"
    "                this._settings.customStylesEnabled.value = false;\n"
    "                this._settings.customStylesFailed.value = true;\n"
    "            }\n"
    "        }\n"
    "        outputStream.close(null);\n"
    "        stream.close(null);\n"
    "        this._dynamicStyleSheet = file;\n"
    "        _cachedStyleSheet = file;\n"
    "        _cachedStyles = styles;\n"
    "        _cachedTheme = theme;\n"
    "    }\n"
    "    _unloadStyleSheet() {\n"
    "        const sheet = this._dynamicStyleSheet || _cachedStyleSheet;\n"
    "        if (sheet) {\n"
    "            const theme = _cachedTheme || St.ThemeContext.get_for_stage(global.stage).get_theme();\n"
    "            try {\n"
    "                theme.unload_stylesheet(sheet);\n"
    "            }\n"
    "            catch (_e) {}\n"
    "            try {\n"
    "                sheet.delete(null);\n"
    "            }\n"
    "            catch (e) {\n"
    "                console.warn('Failed to delete temporary stylesheet file:', e);\n"
    "            }\n"
    "            this._dynamicStyleSheet = undefined;\n"
    "            _cachedStyleSheet = null;\n"
    "            _cachedStyles = null;\n"
    "            _cachedTheme = null;\n"
    "        }\n"
    "    }"
)

assert old_methods in src, "Methods block not found in Styles.js"
src = src.replace(old_methods, new_methods, 1)

with open(styles_path, "w") as f:
    f.write(src)
